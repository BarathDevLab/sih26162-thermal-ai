def bootstrap_alerts():
    """
    Generates operational alerts for current high-severity anomalies using DecisionEngine.
    Finds sites where Model C is ELEVATED, ANOMALOUS, or CRITICAL, or Model B is REACTIVATED.
    """
    t0 = time.time()
    logger.info("Evaluating initial operational alerts from DecisionEngine...")
    engine_inst = DecisionEngine()

    db = SessionLocal()
    try:
        results = (
            db.query(
                SiteModelC.site_id,
                SiteModelC.event_date,
                SiteModelC.operational_status,
                SiteModelA.decision.label("a_decision"),
                SiteModelA.core_probability.label("a_prob"),
                SiteModelB.state.label("b_state")
            )
            .join(SiteModelA, SiteModelC.site_id == SiteModelA.site_id)
            .join(SiteModelB, SiteModelC.site_id == SiteModelB.site_id)
            .filter(
                (SiteModelC.operational_status.in_(["CRITICAL", "ANOMALOUS", "ELEVATED"])) |
                (SiteModelB.state == "REACTIVATED")
            )
            .all()
        )

        logger.info(f"Evaluating {len(results)} candidate sites for alert generation...")
        alert_records = []
        seen_fps = set()
        for r in results:
            site_id, event_date, c_status, a_dec, a_prob, b_state = r
            dt_str = str(event_date) if event_date else "2025-12-31"

            eval_res = engine_inst.evaluate(
                site_id=site_id,
                site_day=dt_str,
                model_a_result={"decision": a_dec, "core_probability": a_prob},
                model_b_result={"state": b_state},
                model_c_result={"status": c_status}
            )

            if eval_res.get("alert_type") != "NO_ALERT":
                fp = eval_res.get("alert_fingerprint") or eval_res.get("fingerprint")
                if not fp or fp in seen_fps:
                    continue
                seen_fps.add(fp)

                alert_id = f"ALT_{site_id}_{dt_str}_{eval_res['alert_type']}"
                alert_day = event_date if event_date else datetime.strptime(dt_str, "%Y-%m-%d").date()
                alert_records.append({
                    "alert_id": alert_id,
                    "site_id": site_id,
                    "site_day": alert_day,
                    "alert_type": eval_res["alert_type"],
                    "alert_level": eval_res["alert_level"],
                    "headline": eval_res["headline"],
                    "reason_codes": eval_res.get("reason_codes", []),
                    "evidence_required": eval_res.get("evidence_required", False),
                    "fingerprint": fp,
                    "status": "ACTIVE",
                    "is_escalation": eval_res.get("is_escalation", False),
                    "created_at": datetime.now(timezone.utc),
                    "updated_at": datetime.now(timezone.utc)
                })

        for chunk_idx in range(0, len(alert_records), 1000):
            chunk = alert_records[chunk_idx:chunk_idx + 1000]
            db.bulk_insert_mappings(Alert, chunk)
            db.commit()

        logger.info(f"Generated and stored {len(alert_records)} operational alerts in {time.time()-t0:.2f}s.")
        return len(alert_records)
    finally:
        db.close()


