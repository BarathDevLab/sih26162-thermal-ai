def clean_dict_for_json(d: dict) -> dict:
    """Recursively replaces NaN with None for valid JSON serialization."""
    clean = {}
    for k, v in d.items():
        if isinstance(v, float) and (np.isnan(v) or np.isinf(v)):
            clean[k] = None
        elif pd.isna(v):
            clean[k] = None
        elif isinstance(v, dict):
            clean[k] = clean_dict_for_json(v)
        else:
            clean[k] = v
    return clean


